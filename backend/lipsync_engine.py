def _mesh_instance():
    global _mesh
    if mp is not None and hasattr(mp, 'solutions') and _mesh is None:
        _mesh = mp.solutions.face_mesh.FaceMesh(
            static_image_mode=False, max_num_faces=1, refine_landmarks=False,
            min_detection_confidence=.5, min_tracking_confidence=.5,
        )
    return _mesh


def _detect_bbox(frame):
    """Return a stable full-face/jaw box and reuse it for near-identical frames."""
    global _last_bbox, _last_small
    height, width = frame.shape[:2]
    small = cv2.resize(cv2.cvtColor(frame, cv2.COLOR_BGR2GRAY), (32, 32))
    if _last_small is not None and np.mean(cv2.absdiff(small, _last_small)) < 2.5 and _last_bbox is not None:
        return _last_bbox
    bbox = None
    mesh = _mesh_instance()
    if mesh is not None:
        result = mesh.process(cv2.cvtColor(frame, cv2.COLOR_BGR2RGB))
        if result.multi_face_landmarks:
            points = np.asarray([(p.x * width, p.y * height) for p in result.multi_face_landmarks[0].landmark])
            x1, y1 = np.maximum(points.min(axis=0) - (width * .025, height * .025), 0).astype(int)
            x2, y2 = np.minimum(points.max(axis=0) + (width * .025, height * .05), (width - 1, height - 1)).astype(int)
            bbox = (int(x1), int(y1), int(x2), int(y2))
    if bbox is None:
        cascade = cv2.CascadeClassifier(cv2.data.haarcascades + 'haarcascade_frontalface_default.xml')
        faces = cascade.detectMultiScale(small, scaleFactor=1.15, minNeighbors=5)
        if len(faces):
            x, y, w, h = faces[0] * np.array([width / 32, height / 32, width / 32, height / 32])
            bbox = (int(x), int(y), int(x + w), int(y + h))
    _last_small, _last_bbox = small, bbox
    return bbox


def _keypoints_for_bbox(bbox):
    keypoints = np.zeros((1, 91, 2), dtype=np.float32)
    if bbox is None:
        return keypoints
    x1, y1, x2, y2 = bbox
    center_x, center_y = (x1 + x2) / 2, (y1 + y2) / 2
    radius_x, radius_y = (x2 - x1) / 2, (y2 - y1) / 2
    angles = np.linspace(0, 2 * np.pi, 68, endpoint=False)
    face = np.column_stack((center_x + radius_x * np.cos(angles), center_y + radius_y * np.sin(angles)))
    # The upstream bbox logic reads these lower-face landmarks specifically.
    face[28], face[29], face[30] = (center_x, y1 + radius_y * .84), (center_x, y1 + radius_y), (center_x, y1 + radius_y * 1.16)
    keypoints[0, 23:91] = face
    return keypoints


