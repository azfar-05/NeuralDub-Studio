def _patch_legacy_torch_loads() -> None:
    """Opt out of PyTorch 2.6's legacy-checkpoint ``weights_only`` default.

    MuseTalk carries legacy tar checkpoints for face parsing, S3FD, Whisper and
    optional training utilities.  These are project-controlled checkpoints, so
    they must be deliberately loaded with ``weights_only=False``.  The patch is
    source-idempotent and writes a file only when an unpatched call remains.
    """
    replacements = {
        "torch.load(model_path)": "torch.load(model_path, weights_only=False)",
        "torch.load(model_pth)": "torch.load(model_pth, weights_only=False)",
        "torch.load(model_pth, map_location=torch.device('cpu'))": "torch.load(model_pth, map_location=torch.device('cpu'), weights_only=False)",
        "torch.load(path_to_detector)": "torch.load(path_to_detector, weights_only=False)",
        "torch.load(pretrained_unet_path, map_location=accelerator.device)": "torch.load(pretrained_unet_path, map_location=accelerator.device, weights_only=False)",
        "torch.load(fp, map_location=device)": "torch.load(fp, map_location=device, weights_only=False)",
        "torch.load(\n            syncnet_config.ckpt.inference_ckpt_path, map_location=accelerator.device)": "torch.load(\n            syncnet_config.ckpt.inference_ckpt_path, map_location=accelerator.device, weights_only=False)",
    }
    for path in (REPO_DIR / "musetalk").rglob("*.py"):
        text = path.read_text(encoding="utf-8")
        patched = text
        for old, new in replacements.items():
            patched = patched.replace(old, new)
        # Catch simple one-line loads introduced by compatible upstream changes.
        patched = re.sub(
            r"torch\.load\(([^\n()]+)\)(?!\s*,)",
            lambda match: match.group(0) if "weights_only=" in match.group(1) else f"torch.load({match.group(1)}, weights_only=False)",
            patched,
        )
        if patched != text:
            path.write_text(patched, encoding="utf-8")


def _patch_musetalk_runtime() -> None:
    """Make the upstream inference path safe for CUDA, MPS, and CPU.

    MuseTalk's stock entrypoint selects CUDA-or-CPU and enables half precision
    from a CLI flag.  The generated adapter adds MPS selection for PyTorch
    models, keeps MPS in float32, and leaves the upstream S3FD detector on CPU
    because that detector only accepts CPU/CUDA device strings.
    """
    adapter = REPO_DIR / "musetalk" / "utils" / "neuraldub_runtime.py"
    _write_text_if_changed(adapter, _musetalk_runtime_source())
    mediapipe_fallback = REPO_DIR / "musetalk" / "utils" / "neuraldub_mediapipe.py"
    _write_text_if_changed(mediapipe_fallback, _musetalk_mediapipe_source())
    inference = REPO_DIR / "scripts" / "inference.py"
    _replace_once(
        inference,
        "from transformers import WhisperModel\nimport sys\n",
        "from transformers import WhisperModel\nimport sys\nfrom musetalk.utils.neuraldub_runtime import get_torch_device, use_float16\n",
    )
    _replace_once(
        inference,
        'device = torch.device(f"cuda:{args.gpu_id}" if torch.cuda.is_available() else "cpu")',
        "device = get_torch_device(args.gpu_id)\n    # MPS is deliberately fp32: fp16 has unsupported MuseTalk kernels.\n    args.use_float16 = bool(args.use_float16 and use_float16(device))",
    )
    preprocessing = REPO_DIR / "musetalk" / "utils" / "preprocessing.py"
    _replace_once(
        preprocessing,
        "from mmpose.apis import inference_topdown, init_model\nfrom mmpose.structures import merge_data_samples\n",
        "try:\n    from mmpose.apis import inference_topdown, init_model\n    from mmpose.structures import merge_data_samples\n    HAS_MMPOSE = True\nexcept ImportError:\n    from musetalk.utils.neuraldub_mediapipe import inference_topdown, install_detector_fallback, merge_data_samples\n    init_model = None\n    HAS_MMPOSE = False\n",
    )
    _replace_once(
        preprocessing,
        "from tqdm import tqdm\n",
        "from tqdm import tqdm\nfrom musetalk.utils.neuraldub_runtime import get_face_detection_device, get_torch_device\n",
    )
    _patch_dwpose_initialization(preprocessing)
    _patch_face_detector_initialization(preprocessing)
    _patch_legacy_torch_loads()


def _ensure_repo_models_link(weights: Path) -> None:
    """Expose managed checkpoints at the relative path expected by MuseTalk."""
    link = REPO_DIR / "models"
    if link.exists() and not link.is_symlink():
        # Preserve a user-managed directory while exposing every required
        # managed checkpoint through relative paths used by upstream MuseTalk.
        for name in ("musetalkV15", "sd-vae-ft-mse", "whisper", "dwpose", "face-parse-bisent"):
            target = weights / name
            child = link / name
            if target.exists() and not child.exists():
                child.symlink_to(target, target_is_directory=True)
        return
    if link.is_symlink() and link.resolve() == weights.resolve():
        return
    if link.is_symlink():
        link.unlink()
    link.symlink_to(weights, target_is_directory=True)


def _download_if_missing(repo_id: str, destination: Path, required: tuple[Path, ...], patterns: list[str]) -> None:
    """Download a narrow Hugging Face snapshot only when a required file is absent."""
    if all(path.is_file() for path in required):
        return
    try:
        from huggingface_hub import snapshot_download

        snapshot_download(repo_id=repo_id, local_dir=str(destination), allow_patterns=patterns)
    except ImportError as exc:
        raise RuntimeError("Install huggingface_hub to download MuseTalk weights.") from exc
    missing = [str(path.relative_to(MODELS_DIR)) for path in required if not path.is_file()]
    if missing:
        raise RuntimeError(f"Checkpoint download completed but files are missing: {', '.join(missing)}")


def _ensure_face_parse_weights() -> None:
    """Download the two upstream Face Parse BiSeNet checkpoints on demand."""
    destination = MODELS_DIR / "face-parse-bisent"
    bisenet = destination / "79999_iter.pth"
    resnet = destination / "resnet18-5c106cde.pth"
    if bisenet.is_file() and resnet.is_file():
        return
    destination.mkdir(parents=True, exist_ok=True)
    if not bisenet.is_file():
        try:
            import gdown

            downloaded = gdown.download(id="154JgKpzCPW82qINcVieuPH3fZ2e0P812", output=str(bisenet), quiet=False)
        except ImportError as exc:
            raise RuntimeError("Install gdown to download MuseTalk face-parsing weights.") from exc
        if not downloaded or not bisenet.is_file():
            raise RuntimeError("Could not download MuseTalk face-parsing checkpoint 79999_iter.pth.")
    if not resnet.is_file():
        urllib.request.urlretrieve("https://download.pytorch.org/models/resnet18-5c106cde.pth", resnet)


def ensure_musetalk_weights() -> Path:
    """Fetch the MuseTalk source and official V1.5 checkpoints when absent."""
    if not REPO_DIR.is_dir():
        if shutil.which("git") is None:
            raise RuntimeError("git is required to download MuseTalk on first use.")
        result = subprocess.run(["git", "clone", "--depth", "1", "https://github.com/TMElyralab/MuseTalk.git", str(REPO_DIR)],
                                capture_output=True, text=True, check=False)
        if result.returncode:
            raise RuntimeError(f"Could not clone MuseTalk: {result.stderr.strip()}")
    MODELS_DIR.mkdir(parents=True, exist_ok=True)
    _download_if_missing(
        "TMElyralab/MuseTalk", MODELS_DIR,
        (MODELS_DIR / "musetalkV15" / "unet.pth", MODELS_DIR / "musetalkV15" / "musetalk.json"),
        ["musetalkV15/*", "sd-vae-ft-mse/*", "whisper/*", "dwpose/*", "face-parse-bisent/*"],
    )
    _download_if_missing(
        "yzd-v/DWPose", MODELS_DIR / "dwpose",
        (MODELS_DIR / "dwpose" / "dw-ll_ucoco_384.pth",),
        ["dw-ll_ucoco_384.pth"],
    )
    _ensure_face_parse_weights()
    _download_if_missing(
        "stabilityai/sd-vae-ft-mse", MODELS_DIR / "sd-vae-ft-mse",
        (MODELS_DIR / "sd-vae-ft-mse" / "config.json",),
        ["config.json", "diffusion_pytorch_model.safetensors", "diffusion_pytorch_model.bin"],
    )
    _download_if_missing(
        "openai/whisper-tiny", MODELS_DIR / "whisper",
        (MODELS_DIR / "whisper" / "config.json",),
        ["config.json", "model.safetensors", "pytorch_model.bin", "preprocessor_config.json", "tokenizer.json", "vocab.json", "merges.txt"],
    )
    _ensure_repo_models_link(MODELS_DIR)
    _patch_musetalk_runtime()
    return MODELS_DIR


def _newest_video(directories: tuple[Path, ...], excluded: tuple[Path, ...]) -> Path | None:
    """Find a non-empty MuseTalk render across current and legacy result roots."""
    ignored = {path.resolve() for path in excluded}
    videos: list[Path] = []
    for directory in directories:
        if not directory.is_dir():
            continue
        for candidate in directory.rglob("*.mp4"):
            if candidate.resolve() not in ignored and candidate.is_file() and candidate.stat().st_size > 0:
                videos.append(candidate)
    return max(videos, key=lambda path: path.stat().st_mtime) if videos else None


def _mux_generated_frames(result_roots: tuple[Path, ...], audio_path: Path, output_path: Path) -> bool:
    """Assemble retained numbered MuseTalk PNG frames when its internal mux fails."""
    frame_directories: list[Path] = []
    for root in result_roots:
        if root.is_dir():
            frame_directories.extend(path.parent for path in root.rglob("*.png") if path.name == "00000000.png")
    if not frame_directories:
        return False
    frames = max(frame_directories, key=lambda path: sum(1 for _ in path.glob("*.png")))
    if not any(frames.glob("*.png")):
        return False
    _run_ffmpeg([
        "ffmpeg", "-y", "-framerate", "25", "-start_number", "0", "-i", str(frames / "%08d.png"),
        "-i", str(audio_path), "-map", "0:v:0", "-map", "1:a:0?", "-c:v", "libx264", "-pix_fmt", "yuv420p",
        "-c:a", "aac", "-shortest", str(output_path),
    ])
    return output_path.is_file() and output_path.stat().st_size > 0


def _process_diagnostics(process: subprocess.CompletedProcess[str]) -> str:
    """Keep actionable MuseTalk output in the API error without overwhelming it."""
    stdout, stderr = (process.stdout or "").strip(), (process.stderr or "").strip()
    details = "\n".join(part for part in (stderr[-4000:], stdout[-4000:]) if part)
    return details or "MuseTalk emitted no stdout or stderr."


def _create_comparison(original_video: Path, synced_video: Path, output: Path) -> list[float]:
    """Create 256px mouth comparison video and a visual/audio alignment timeline."""
    try:
        import cv2
        import numpy as np
        import librosa
    except ImportError as exc:
        raise RuntimeError("Install opencv-python, numpy and librosa for lip telemetry.") from exc

    original = cv2.VideoCapture(str(original_video))
    synced = cv2.VideoCapture(str(synced_video))
    fps = original.get(cv2.CAP_PROP_FPS) or 25.0
    count = int(min(original.get(cv2.CAP_PROP_FRAME_COUNT), synced.get(cv2.CAP_PROP_FRAME_COUNT)))
    if count <= 0:
        raise RuntimeError("Could not read frames for mouth comparison.")
    temporary = output.with_suffix(".silent.mp4")
    writer = cv2.VideoWriter(str(temporary), cv2.VideoWriter_fourcc(*"mp4v"), fps, (512, 256))
    movement: list[float] = []
    previous: Any | None = None
    for _ in range(count):
        ok_a, frame_a = original.read()
        ok_b, frame_b = synced.read()
        if not (ok_a and ok_b):
            break
        def mouth(frame: Any) -> Any:
            height, width = frame.shape[:2]
            # Lower-central crop is stable and avoids retaining a face detector.
            crop = frame[int(height * .48):int(height * .92), int(width * .20):int(width * .80)]
            return cv2.resize(crop, (256, 256), interpolation=cv2.INTER_AREA)
        left, right = mouth(frame_a), mouth(frame_b)
        gray = cv2.cvtColor(right, cv2.COLOR_BGR2GRAY)
        movement.append(0.0 if previous is None else float(np.mean(cv2.absdiff(gray, previous))))
        previous = gray
        writer.write(np.hstack((left, right)))
    original.release(); synced.release(); writer.release()

    # Compare mouth motion with audio energy at matching frame timestamps.
    audio, sample_rate = librosa.load(str(synced_video), sr=16000, mono=True)
    hop = max(1, round(sample_rate / fps))
    energy = librosa.feature.rms(y=audio, frame_length=hop * 2, hop_length=hop)[0]
    timeline: list[float] = []
    for index, value in enumerate(movement):
        start, end = max(0, index - 3), min(len(movement), index + 4)
        visual = np.asarray(movement[start:end], dtype=float)
        audible = np.asarray(energy[start:min(end, len(energy))], dtype=float)
        length = min(visual.size, audible.size)
        if length < 2 or np.std(visual[:length]) == 0 or np.std(audible[:length]) == 0:
            timeline.append(0.0)
        else:
            timeline.append(round(float((np.corrcoef(visual[:length], audible[:length])[0, 1] + 1) / 2), 4))
    _run_ffmpeg(["ffmpeg", "-y", "-i", str(temporary), "-i", str(synced_video), "-map", "0:v:0", "-map", "1:a:0?", "-c:v", "libx264", "-c:a", "aac", "-shortest", str(output)])
    temporary.unlink(missing_ok=True)
    return timeline


def run_lipsync(video_path: str, audio_path: str, output_video_path: str,
                custom_unet_path: str | None = None) -> dict[str, Any]:
    """Run MuseTalk V1.5 at 256px and return output paths plus sync confidence."""
    video, audio = Path(video_path).resolve(), Path(audio_path).resolve()
    output = Path(output_video_path).resolve()
    if not video.is_file() or not audio.is_file():
        raise FileNotFoundError("Both input video and synthesized audio must exist.")
    if custom_unet_path and not Path(custom_unet_path).is_file():
        custom_unet_path = None
    output.parent.mkdir(parents=True, exist_ok=True); OUTPUTS_DIR.mkdir(exist_ok=True)
    ffmpeg_path = shutil.which("ffmpeg")
    if ffmpeg_path is None:
        raise RuntimeError("ffmpeg is required for MuseTalk frame assembly but was not found on PATH.")
    config_file: Path | None = None
    try:
        weights = ensure_musetalk_weights()
        with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as handle:
            config_file = Path(handle.name)
            # MuseTalk's inference runner consumes a mapping of named tasks.
            json.dump({"task_0": {"video_path": str(video), "audio_path": str(audio), "bbox_shift": 0,
                                   "result_name": output.name}}, handle)
        device = get_device()
        command = [
            sys.executable, "-m", "scripts.inference", "--inference_config", str(config_file),
            "--result_dir", str(output.parent), "--vae_type", str(weights / "sd-vae-ft-mse"),
            "--unet_config", str(weights / "musetalkV15" / "musetalk.json"),
            "--unet_model_path", custom_unet_path or str(weights / "musetalkV15" / "unet.pth"),
            "--whisper_dir", str(weights / "whisper"), "--batch_size", "8" if device == "cuda" else "4" if device == "mps" else "1",
            "--version", "v15", "--output_vid_name", output.name,
        ]
        if device == "cuda":
            command.append("--use_float16")
        environment = os.environ.copy()
        environment["NEURALDUB_TORCH_DEVICE"] = device
        # CTranslate2 cannot run on MPS. If a patched/third-party MuseTalk
        # component imports faster-whisper, it must choose this CPU int8 mode.
        environment["NEURALDUB_CTRANSLATE2_DEVICE"] = "cuda" if device == "cuda" else "cpu"
        environment["NEURALDUB_CTRANSLATE2_COMPUTE_TYPE"] = "float16" if device == "cuda" else "int8"
        environment["TORCH_FORCE_NO_WEIGHTS_ONLY_LOAD"] = "1"
        environment["PATH"] = str(Path(ffmpeg_path).parent) + os.pathsep + environment.get("PATH", "")
        if device == "mps":
            environment["PYTORCH_ENABLE_MPS_FALLBACK"] = "1"
        process = subprocess.run(command, cwd=REPO_DIR, env=environment, capture_output=True, text=True, check=False)
        result_roots = (output.parent, REPO_DIR / "results")
        rendered = _newest_video(result_roots, (output, video))
        if rendered is None:
            try:
                _mux_generated_frames(result_roots, audio, output)
            except RuntimeError as mux_error:
                raise RuntimeError(
                    f"MuseTalk created no MP4 and fallback frame mux failed: {mux_error}\n{_process_diagnostics(process)}"
                ) from mux_error
            rendered = _newest_video(result_roots, (video,))
        if rendered is None:
            raise RuntimeError(
                f"MuseTalk completed without creating an MP4 result (exit {process.returncode}).\n{_process_diagnostics(process)}"
            )
        if rendered.resolve() != output.resolve():
            shutil.move(str(rendered), str(output))
        # Keep job artifacts together so simultaneous API jobs cannot overwrite
        # each other's comparison clip.
        mouth_zoom = output.parent / "mouth_zoom.mp4"
        scores = _create_comparison(video, output, mouth_zoom)
        return {"dubbed_video": str(output), "mouth_zoom": str(mouth_zoom), "sync_metrics": scores}
    finally:
        if config_file is not None:
            config_file.unlink(missing_ok=True)
        # Model objects lived only in the completed child process; still clear
        # parent-side accelerator allocator before the server starts another job.
        flush_memory()
