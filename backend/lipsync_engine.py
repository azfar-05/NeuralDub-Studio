def _replace_once(path: Path, old: str, new: str) -> None:
    """Apply a known upstream patch once, failing loudly if upstream changed."""
    text = path.read_text(encoding="utf-8")
    if new in text:
        return
    if old not in text:
        raise RuntimeError(f"Unsupported MuseTalk checkout: expected code not found in {path.relative_to(REPO_DIR)}")
    path.write_text(text.replace(old, new, 1), encoding="utf-8")


def _write_text_if_changed(path: Path, content: str) -> bool:
    """Write generated source only when it changed, preserving reload stability."""
    if path.is_file() and path.read_text(encoding="utf-8") == content:
        return False
    path.write_text(content, encoding="utf-8")
    return True


def _replace_any(path: Path, candidates: tuple[str, ...], new: str) -> None:
    """Replace one of several known upstream/past-patch forms idempotently."""
    text = path.read_text(encoding="utf-8")
    marker = "# NeuralDub DWPose backend selection"
    if marker in new and marker in text:
        return
    if marker not in new and new in text:
        return
    for old in candidates:
        if old in text:
            path.write_text(text.replace(old, new, 1), encoding="utf-8")
            return
    raise RuntimeError(f"Unsupported MuseTalk checkout: expected code not found in {path.relative_to(REPO_DIR)}")


def _patch_dwpose_initialization(path: Path) -> None:
    """Replace the complete upstream DWPose initialization block safely.

    Replacing the bounded block, rather than individual nested ``try`` lines,
    keeps the patch idempotent across fresh clones and prior patch versions.
    """
    text = path.read_text(encoding="utf-8")
    start_marker = "# initialize the mmpose model"
    end_marker = "# initialize the face detection model"
    start, end = text.find(start_marker), text.find(end_marker)
    if start < 0 or end < 0 or end <= start:
        raise RuntimeError(f"Unsupported MuseTalk checkout: DWPose block missing from {path.relative_to(REPO_DIR)}")
    replacement = '''# initialize the mmpose model
device = get_torch_device()
config_file = './musetalk/utils/dwpose/rtmpose-l_8xb32-270e_coco-ubody-wholebody-384x288.py'
checkpoint_file = './models/dwpose/dw-ll_ucoco_384.pth'
# NeuralDub DWPose backend selection
if HAS_MMPOSE:
    try:
        model = init_model(config_file, checkpoint_file, device=device)
    except (RuntimeError, ValueError) as error:
        # Some OpenMMLab builds lack MPS kernels; use CPU only for DWPose.
        print(f'DWPose falling back to CPU: {error}')
        device = torch.device('cpu')
        model = init_model(config_file, checkpoint_file, device=device)
else:
    model = None

'''
    patched = text[:start] + replacement + text[end:]
    if patched != text:
        path.write_text(patched, encoding="utf-8")


